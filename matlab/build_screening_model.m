function build_screening_model(metricsFile)
% BUILD_SCREENING_MODEL  Build a SimEvents model of one DR screening-camp day.
%
%   build_screening_model                 uses default accuracy figures
%   build_screening_model('../models/metrics.json')
%
% UNTESTED: written without access to MATLAB. Counterpart of
% fundalux/screening_sim.py, which is tested and is the reference.
%
% Flow (time unit: minutes)
%   Arrivals -> Registration queue/server -> Camera queue/server
%            -> switch: AI negative -> Discharged
%                       AI positive or ungradable -> Review queue
%                                                 -> Ophthalmologist -> Referred
%
% Simplifications compared with the Python model: retakes are folded into the
% imaging service time, and the ophthalmologist reads continuously instead of
% in one session after the camp closes.

    p = struct('patientsPerDay', 80, 'campHours', 6, 'nRegistration', 1, ...
               'nCameras', 2, 'nOphthalmologists', 1, 'prevalence', 0.10, ...
               'pUngradable', 0.15, 'maxRetakes', 2, ...
               'sensitivity', 0.90, 'specificity', 0.85);
    if nargin > 0 && isfile(metricsFile)
        m = jsondecode(fileread(metricsFile));
        s = m.simulation_inputs;
        if ~isempty(s.sensitivity),  p.sensitivity = s.sensitivity;  end
        if ~isempty(s.specificity),  p.specificity = s.specificity;  end
        if ~isempty(s.p_ungradable), p.pUngradable = s.p_ungradable; end
    end

    mdl = 'fundalux_screening';
    if bdIsLoaded(mdl), close_system(mdl, 0); end
    new_system(mdl);
    open_system(mdl);
    set_param(mdl, 'StopTime', num2str(24 * 60));

    lib = 'simeventslib/';
    blk = @(name) [mdl '/' name];

    % --- Patients: exponential inter-arrival times; each carries its outcome.
    meanGap = p.campHours * 60 / p.patientsPerDay;
    add_block([lib 'Entity Generator'], blk('Arrivals'), ...
        'EntityType', 'Structured', ...
        'AttributeName', 'diseased|route', ...
        'AttributeInitialValue', '0|1', ...
        'TimeSource', 'MATLAB action', ...
        'IntergenerationTimeAction', sprintf('dt = -%g * log(1 - rand());', meanGap), ...
        'GenerateAction', sprintf('entity.diseased = double(rand() < %g);', p.prevalence));

    add_block([lib 'Entity Queue'], blk('Registration queue'), 'Capacity', 'Inf');
    add_block([lib 'Entity Server'], blk('Registration'), ...
        'Capacity', num2str(p.nRegistration), ...
        'ServiceTimeSource', 'MATLAB action', ...
        'ServiceTimeAction', 'dt = 1 + 3 * rand();');

    % --- Imaging: one attempt takes 3-9 min; an ungradable photo is retaken on
    %     the spot. route = 1 discharge, 2 refer (AI positive or still ungradable).
    imaging = sprintf([ ...
        'dt = 0; attempts = 0; gradable = false;\n' ...
        'while ~gradable && attempts <= %d\n' ...
        '    attempts = attempts + 1;\n' ...
        '    dt = dt + 3 + 6 * rand();\n' ...
        '    gradable = rand() >= %g;\n' ...
        'end\n'], p.maxRetakes, p.pUngradable);
    grading = sprintf([ ...
        'pPositive = %g;\n' ...
        'if entity.diseased == 1, pPositive = %g; end\n' ...
        'entity.route = 1 + double(rand() < %g || rand() < pPositive);\n'], ...
        1 - p.specificity, p.sensitivity, p.pUngradable ^ (p.maxRetakes + 1));
    add_block([lib 'Entity Queue'], blk('Camera queue'), 'Capacity', 'Inf');
    add_block([lib 'Entity Server'], blk('Imaging and AI grading'), ...
        'Capacity', num2str(p.nCameras), ...
        'ServiceTimeSource', 'MATLAB action', ...
        'ServiceTimeAction', imaging, ...
        'ServiceCompleteAction', grading);

    add_block([lib 'Entity Output Switch'], blk('AI decision'), ...
        'NumberOutputPorts', '2', ...
        'SwitchingCriterion', 'From attribute', ...
        'SwitchAttributeName', 'route');
    add_block([lib 'Entity Terminator'], blk('Discharged'));

    add_block([lib 'Entity Queue'], blk('Review queue'), 'Capacity', 'Inf');
    add_block([lib 'Entity Server'], blk('Ophthalmologist'), ...
        'Capacity', num2str(p.nOphthalmologists), ...
        'ServiceTimeSource', 'MATLAB action', ...
        'ServiceTimeAction', 'dt = 2 + 6 * rand();');
    add_block([lib 'Entity Terminator'], blk('Referred'));

    add_line(mdl, 'Arrivals/1', 'Registration queue/1');
    add_line(mdl, 'Registration queue/1', 'Registration/1');
    add_line(mdl, 'Registration/1', 'Camera queue/1');
    add_line(mdl, 'Camera queue/1', 'Imaging and AI grading/1');
    add_line(mdl, 'Imaging and AI grading/1', 'AI decision/1');
    add_line(mdl, 'AI decision/1', 'Discharged/1');
    add_line(mdl, 'AI decision/2', 'Review queue/1');
    add_line(mdl, 'Review queue/1', 'Ophthalmologist/1');
    add_line(mdl, 'Ophthalmologist/1', 'Referred/1');

    Simulink.BlockDiagram.arrangeSystem(mdl);
    save_system(mdl);
    fprintf(['Built %s.slx. Turn on the statistics ports you want (queue length, ' ...
             'average wait, utilisation) in the Statistics tab of each block, ' ...
             'then run the model.\n'], mdl);
end
